import { it } from 'vitest';
import { makeTown, tempDb } from './helpers.js';
it('probe', () => {
  const db = tempDb();
  const t = makeTown({ dbPath: db.path });
  const a = t.join('阿灯'); const b = t.join('小岚', 'agent');
  a.go('tea_house'); b.go('tea_house');
  a.act('buy', { shop: 'tea_counter', sku: 'tea_leaves', qty: 1 });
  const table = a.view().here!.objects.find((o) => o.type === 'tea_table')!;
  const ix = a.act('start_interaction', { objectId: table.id });
  b.act('join_interaction', { interactionId: ix.interaction.id });
  a.act('begin_interaction', { interactionId: ix.interaction.id });
  const offerA = a.act('offer', { kind: 'gift', to: b.residentId, give: { coins: 1 } });
  console.log('ix', t.w.db.all('SELECT status, started_at, ends_at FROM interactions'));
  console.log('offer', offerA.offer.status);
  const t0 = t.clock.t;
  t.w.close(); t.clock.advance(2*3600_000);
  t.restart();
  console.log('ix', t.w.db.all('SELECT status, started_at, ends_at, closed_at, close_reason FROM interactions'), t0);
  console.log('offers', t.w.db.all('SELECT status, closed_at, close_reason FROM offers'));
  console.log('jobs', t.w.db.all("SELECT dedupe_key,status,due_at,processed_at FROM scheduled_jobs"));
  console.log('ev', t.w.db.all("SELECT resident_id,cursor,type,occurred_at,created_at FROM recipient_events WHERE resident_id=?", a.residentId).slice(-8));
  console.log('pub', t.w.db.all("SELECT cursor,type,occurred_at FROM public_events").slice(-5));
  console.log(a.row().present_since, a.row().last_seen_at, t.clock.t, t.logs);
  db.cleanup();
});
